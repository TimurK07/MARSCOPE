"""Fetch the assets for the 3D Mars globe.

1. A low-resolution copy of the Viking MDIM 2.1 colorized global mosaic, used as
   the instant first texture of the globe. Source: USGS Astrogeology WMS
   (layer MDIM21_color; the service declares Fees: None, AccessConstraints: None).
   Credit: NASA/JPL/USGS.
2. Centre coordinates of a few named features from the IAU/USGS Gazetteer of
   Planetary Nomenclature, used for labels on the globe.

Usage:
    python scripts/fetch_globe_assets.py

Outputs:
    app/public/data/mars/viking_mdim21_2048.jpg
    app/src/lib/marsFeatures.ts
"""

from __future__ import annotations

import io
import json
import struct
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEXTURE = ROOT / "app" / "public" / "data" / "mars" / "viking_mdim21_2048.jpg"
FEATURES = ROOT / "app" / "src" / "lib" / "marsFeatures.ts"

WMS = (
    "https://planetarymaps.usgs.gov/cgi-bin/mapserv?map=/maps/mars/mars_simp_cyl.map"
    "&SERVICE=WMS&VERSION=1.1.1&REQUEST=GetMap&LAYERS=MDIM21_color&STYLES=&SRS=EPSG:4326"
    "&BBOX=-180,-90,180,90&WIDTH=2048&HEIGHT=1024&FORMAT=image/jpeg"
)
GAZETTEER = "https://asc-planetarynames-data.s3.us-west-2.amazonaws.com/MARS_nomenclature_center_pts.zip"

# Features labelled on the globe, with the zoom band in which each label shows.
WANTED = {
    "Olympus Mons": "global",
    "Valles Marineris": "global",
    "Hellas Planitia": "global",
    "Tharsis Montes": "global",
    "Elysium Mons": "global",
    "Syrtis Major Planum": "global",
    "Utopia Planitia": "global",
    "Arabia Terra": "global",
    "Argyre Planitia": "global",
    "Acidalia Planitia": "global",
    "Isidis Planitia": "global",
    "Planum Boreum": "global",
    "Planum Australe": "global",
    "Gale": "regional",
    "Aeolis Mons": "local",
    "Jezero": "regional",
}


def get(url: str) -> bytes:
    # The USGS server rejects urllib's default user agent.
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (asset fetch script)"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def read_dbf(data: bytes) -> list[dict[str, str]]:
    count, header_len, record_len = struct.unpack("<IHH", data[4:12])
    fields = []
    off = 32
    while data[off] != 0x0D:
        fields.append((data[off : off + 11].split(b"\0")[0].decode(), data[off + 16]))
        off += 32
    rows = []
    for i in range(count):
        rec = data[header_len + i * record_len : header_len + (i + 1) * record_len]
        pos = 1
        row = {}
        for name, length in fields:
            row[name] = rec[pos : pos + length].decode("latin1").strip()
            pos += length
        rows.append(row)
    return rows


def main() -> None:
    TEXTURE.parent.mkdir(parents=True, exist_ok=True)
    print("Downloading Viking MDIM 2.1 color mosaic, 2048 x 1024")
    TEXTURE.write_bytes(get(WMS))
    print(f"  {TEXTURE.stat().st_size / 1024:.0f} kB -> {TEXTURE.relative_to(ROOT)}")

    print("Downloading IAU/USGS gazetteer")
    archive = zipfile.ZipFile(io.BytesIO(get(GAZETTEER)))
    dbf = next(n for n in archive.namelist() if n.endswith(".dbf"))
    features = []
    for row in read_dbf(archive.read(dbf)):
        if row["name"] in WANTED and row["approval"] == "Adopted by IAU":
            lon = float(row["center_lon"])  # gazetteer: planetocentric, east-positive, 0-360
            features.append(
                {
                    "name": "Gale crater" if row["name"] == "Gale" else "Jezero crater" if row["name"] == "Jezero" else row["name"],
                    "lat": round(float(row["center_lat"]), 4),
                    "lon": round(lon - 360 if lon > 180 else lon, 4),
                    "diameterKm": round(float(row["diameter"]), 1),
                    "band": WANTED[row["name"]],
                }
            )
    features.sort(key=lambda f: f["name"])
    assert len(features) == len(WANTED), f"found {len(features)} of {len(WANTED)}"
    body = ",\n".join("  " + json.dumps(f) for f in features)
    FEATURES.write_text(
        "// Generated by scripts/fetch_globe_assets.py from the IAU/USGS Gazetteer of\n"
        "// Planetary Nomenclature (https://planetarynames.wr.usgs.gov). Do not edit by hand.\n"
        "// Coordinates: planetocentric latitude, east-positive longitude in -180..180.\n\n"
        "export interface MarsFeature {\n  name: string\n  lat: number\n  lon: number\n  diameterKm: number\n"
        "  /** Zoom band in which the label is shown. */\n  band: 'global' | 'regional' | 'local'\n}\n\n"
        f"export const MARS_FEATURES: MarsFeature[] = [\n{body},\n]\n"
    )
    print(f"  {len(features)} features -> {FEATURES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
